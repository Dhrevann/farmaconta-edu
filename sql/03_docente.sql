begin;

create table if not exists public.farma_teachers(
  user_id uuid primary key references auth.users(id) on delete cascade,
  enabled boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.farma_teachers enable row level security;
revoke all on public.farma_teachers from public, anon, authenticated;

create table if not exists public.farma_teacher_reviews(
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  module text not null check(module in ('finanzas','ventas','inventario','contabilidad','reportes','general')),
  score numeric(4,2) not null check(score>=0 and score<=20),
  feedback text not null check(char_length(feedback)<=2000),
  teacher_id uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
create index if not exists farma_reviews_student_idx on public.farma_teacher_reviews(owner_id,created_at desc);
alter table public.farma_teacher_reviews enable row level security;
revoke all on public.farma_teacher_reviews from public, anon, authenticated;
grant select on public.farma_teacher_reviews to authenticated;
drop policy if exists "student reads own teacher reviews" on public.farma_teacher_reviews;
create policy "student reads own teacher reviews" on public.farma_teacher_reviews
 for select to authenticated using (owner_id=(select auth.uid()));

-- Verificación exclusiva del servidor: no basta con ocultar botones al usuario.
create or replace function public.farma_is_teacher()
returns boolean language sql stable security definer set search_path=''
as $$
  select exists(select 1 from public.farma_teachers t
   where t.user_id=(select auth.uid()) and t.enabled);
$$;
revoke all on function public.farma_is_teacher() from public,anon;
grant execute on function public.farma_is_teacher() to authenticated;

create or replace function public.farma_teacher_dashboard()
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_data jsonb;
begin
 if not public.farma_is_teacher() then raise exception 'ACCESS_DENIED'; end if;
 select coalesce(jsonb_agg(jsonb_build_object(
  'user_id',u.id,
  'email',e.email,
  'display_name',coalesce(w.data #>> '{pharmacy,student}',''),
  'pharmacy',coalesce(w.data #>> '{pharmacy,name}',''),
  'sales',case when jsonb_typeof(w.data->'sales')='array' then jsonb_array_length(w.data->'sales') else 0 end,
  'expenses',case when jsonb_typeof(w.data->'expenses')='array' then jsonb_array_length(w.data->'expenses') else 0 end,
  'exercises',case when jsonb_typeof(w.data #> '{learning,answers}')='object' then
     (select count(*) from jsonb_object_keys(w.data #> '{learning,answers}')) else 0 end,
  'evaluations',case when jsonb_typeof(w.data #> '{learning,attempts}')='array' then jsonb_array_length(w.data #> '{learning,attempts}') else 0 end,
  'last_saved',w.updated_at,
  'has_workspace',w.owner_id is not null
 ) order by e.email),'[]'::jsonb) into v_data
 from public.class_enrollments e
 left join auth.users u on lower(u.email)=e.email
 left join public.workspaces w on w.owner_id=u.id;
 return v_data;
end;
$$;
revoke all on function public.farma_teacher_dashboard() from public,anon;
grant execute on function public.farma_teacher_dashboard() to authenticated;

create or replace function public.farma_teacher_student(p_student uuid)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_data jsonb;
begin
 if not public.farma_is_teacher() then raise exception 'ACCESS_DENIED'; end if;
 if not exists(select 1 from public.class_enrollments e join auth.users u on lower(u.email)=e.email
 where u.id=p_student) then raise exception 'STUDENT_NOT_ENROLLED'; end if;
 select w.data into v_data from public.workspaces w where w.owner_id=p_student;
 return coalesce(v_data,'{}'::jsonb);
end;
$$;
revoke all on function public.farma_teacher_student(uuid) from public,anon;
grant execute on function public.farma_teacher_student(uuid) to authenticated;

create or replace function public.farma_teacher_grade(
 p_student uuid,p_module text,p_score numeric,p_feedback text
) returns bigint language plpgsql security definer set search_path=''
as $$
declare v_id bigint;
begin
 if not public.farma_is_teacher() then raise exception 'ACCESS_DENIED'; end if;
 if p_module not in ('finanzas','ventas','inventario','contabilidad','reportes','general') then raise exception 'INVALID_MODULE'; end if;
 if p_score is null or p_score<0 or p_score>20 then raise exception 'INVALID_SCORE'; end if;
 if p_feedback is null or length(p_feedback)>2000 then raise exception 'INVALID_FEEDBACK'; end if;
 if not exists(select 1 from public.class_enrollments e join auth.users u on lower(u.email)=e.email
 where u.id=p_student) then raise exception 'STUDENT_NOT_ENROLLED'; end if;
 insert into public.farma_teacher_reviews(owner_id,module,score,feedback,teacher_id)
 values(p_student,p_module,p_score,p_feedback,auth.uid()) returning id into v_id;
 return v_id;
end;
$$;
revoke all on function public.farma_teacher_grade(uuid,text,numeric,text) from public,anon;
grant execute on function public.farma_teacher_grade(uuid,text,numeric,text) to authenticated;

create or replace function public.farma_teacher_enrollment(p_email text,p_enabled boolean)
returns boolean language plpgsql security definer set search_path=''
as $$
declare v_email text:=lower(trim(p_email));
begin
 if not public.farma_is_teacher() then raise exception 'ACCESS_DENIED'; end if;
 if v_email is null or length(v_email)>254 or v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
   raise exception 'INVALID_EMAIL';
 end if;
 if p_enabled then
   insert into public.class_enrollments(email) values(v_email) on conflict(email) do nothing;
 else
   -- Revocar matrícula NO elimina trabajos ni datos del alumno.
   delete from public.class_enrollments where email=v_email;
 end if;
 return true;
end;
$$;
revoke all on function public.farma_teacher_enrollment(text,boolean) from public,anon;
grant execute on function public.farma_teacher_enrollment(text,boolean) to authenticated;

commit;

